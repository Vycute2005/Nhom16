  static bool get isEnglish => AppLocaleController.isEnglish;

  static String translateRegion(String region) {
    if (!isEnglish) return region;
    return switch (region) {
      'Bắc' => 'North',
      'Trung' => 'Central',
      'Nam' => 'South',
      _ => translate(region),
    };
  }

  static String? translateValidation(String? text) =>
      text == null ? null : translate(text);

  static String translate(String text) {
    if (!isEnglish) return text;

    final exact = _english[text];
    if (exact != null) return exact;

    final savedItemCount = RegExp(r'^(\d+)\s+mục đã lưu$').firstMatch(text);
    if (savedItemCount != null) {
      return savedItemCount.group(1)! + ' saved items';
    }

    for (final entry in _prefixTranslations.entries) {
      if (text.startsWith(entry.key)) {
        return entry.value + text.substring(entry.key.length);
      }
    }
    return text;
  }
